#=======================
#1- Numbers
#=======================
 # Numbers are numeric data types used for arithmetic and mathematical operations.
 # They include integers, floating-point numbers, and complex numbers.
 #(a) Integers

num = 10
print(type(num))

 #(b) Floats
 # Floats represent numbers with a decimal point.

num = 10.5
print(type(num))

 #(c) Complex Numbers
 # Complex numbers have a real part and an imaginary part.

num = 3 + 4j
print(type(num))

#=======================
#2- Strings
#=======================
 # Strings are sequences of characters enclosed in quotes.
 # They are used to store text data.

name = "My name is Prince"
print(type(name))

#=======================
#3- Boolean
#=======================
 # Boolean values represent truth values: True or False.
 # They are commonly used in conditions and logical expressions.

is_true = True
print(type(is_true))

#=======================
#4- List
#=======================
 # Lists are ordered collections of values that can be changed.
 # They allow duplicate items and can hold mixed data types.

my_list = [1, 2, 3, 4, 5]
print(type(my_list))

#=======================
#5- Tuple
#=======================
 # Tuples are ordered collections like lists, but they are immutable.
 # Once created, tuple values cannot be modified.

my_tuple = (1, 2, 3, 4, 5)
print(type(my_tuple))

#=======================
#6- Set
#=======================
 # Sets are unordered collections of unique values.
 # They do not allow duplicate items and support set operations.

my_set = {1, 2, 3, 4, 5}
print(type(my_set))

#=======================
#7- Dictionary
#=======================
 # Dictionaries store key-value pairs.
 # Each key maps to a value, and keys must be unique.
my_dict = {"Name": "Prince", "Age": 31, "Country": "India"}
print(type(my_dict))

