#Data Types
#1- Numbers
 #(a) Integers

Num = 10
print(type(Num))

 #(b) Floats

Num = 10.5
print(type(Num))

 #(c) Complex Numbers

Num = 3 + 4j
print(type(Num))

#2- Strings

Name = "My name is Prince"
print(type(Name))

#3- Boolean

Is_True = True
print(type(Is_True))

#4- List

My_List = [1, 2, 3, 4, 5]
print(type(My_List))

#5- Tuple

My_Tuple = (1, 2, 3, 4, 5)
print(type(My_Tuple))

#6- Set

My_Set = {1, 2, 3, 4, 5}
print(type(My_Set))

#7- Dictionary

My_Dict = {"Name": "Prince", "Age": 31, "Country": "India"}
print(type(My_Dict))

