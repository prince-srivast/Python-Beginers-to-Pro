#=======================
#   Variables
#=======================
 # Variables store values and give those values a name.
 # They can hold different data types and be updated later.

# Assign a value to a variable
name = "Prince"
print(name)

# Change the variable value
age = 31
print(age)
age = 32
print(age)

# Multiple assignment
x, y, z = 1, 2, 3
print(x)
print(y)
print(z)

# Variables can hold different types
value = 10
print(value, type(value))
value = "Hello"
print(value, type(value))
